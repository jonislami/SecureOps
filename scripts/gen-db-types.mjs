#!/usr/bin/env node
/**
 * Generate a Supabase-compatible TypeScript `Database` type by introspecting the
 * live database over the connection pooler (no Docker required, unlike
 * `supabase gen types`). Emits packages/shared/src/types/db.types.ts.
 *
 * Usage: node scripts/gen-db-types.mjs   (reads SUPABASE_DB_URL from .env)
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outFile = join(__dirname, '..', 'packages', 'shared', 'src', 'types', 'db.types.ts');

try {
  const env = readFileSync(join(__dirname, '..', '.env'), 'utf8');
  for (const line of env.split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
} catch {}

const connectionString = process.env.SUPABASE_DB_URL;
if (!connectionString) {
  console.error('SUPABASE_DB_URL not set in .env');
  process.exit(1);
}

const pg = await import('pg');
const { Client } = pg.default ?? pg;
const client = new Client({ connectionString, ssl: { rejectUnauthorized: false } });
await client.connect();

// Tables to exclude from generation (system / partitions / bookkeeping).
const EXCLUDE = new Set(['schema_migrations', 'spatial_ref_sys']);

// --- Enums -----------------------------------------------------------------
const enumsRes = await client.query(`
  select t.typname as name, e.enumlabel as label
  from pg_type t
  join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public'
  order by t.typname, e.enumsortorder;
`);
const enums = {};
for (const r of enumsRes.rows) (enums[r.name] ??= []).push(r.label);
const enumNames = new Set(Object.keys(enums));

// --- Columns (base tables only, skip partitions via relispartition) --------
const colsRes = await client.query(`
  select c.relname as table, a.attname as column,
         format_type(a.atttypid, a.atttypmod) as data_type,
         t.typname as udt_name,
         not a.attnotnull as is_nullable,
         (pg_get_expr(d.adbin, d.adrelid) is not null) as has_default,
         (pg_get_expr(d.adbin, d.adrelid) ilike 'nextval%'
           or pg_get_expr(d.adbin, d.adrelid) ilike '%gen_random_uuid%'
           or a.attidentity <> '') as is_generated
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
  join pg_type t on t.oid = a.atttypid
  left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
  where n.nspname = 'public'
    and c.relkind in ('r','p')          -- ordinary + partitioned parents
    and not c.relispartition             -- skip child partitions
  order by c.relname, a.attnum;
`);

const tables = {};
for (const r of colsRes.rows) {
  if (EXCLUDE.has(r.table)) continue;
  (tables[r.table] ??= []).push(r);
}

function tsType(col) {
  const udt = col.udt_name;
  if (enumNames.has(udt)) return `Database["public"]["Enums"]["${udt}"]`;
  if (udt === 'geography' || udt === 'geometry') return 'string'; // WKB/GeoJSON string
  switch (udt) {
    case 'uuid': case 'text': case 'varchar': case 'bpchar': case 'inet':
    case 'timestamptz': case 'timestamp': case 'date': case 'time': case 'timetz':
      return 'string';
    case 'bool': return 'boolean';
    case 'int2': case 'int4': case 'int8': case 'float4': case 'float8': case 'numeric':
      return 'number';
    case 'json': case 'jsonb': return 'Json';
    default: return 'unknown';
  }
}

let out = `// AUTO-GENERATED by scripts/gen-db-types.mjs — do not edit by hand.
// Regenerate after schema changes: node scripts/gen-db-types.mjs

export type Json =
  | string
  | number
  | boolean
  | null
  | { [key: string]: Json | undefined }
  | Json[];

export type Database = {
  public: {
    Tables: {
`;

for (const table of Object.keys(tables).sort()) {
  const cols = tables[table];
  out += `      ${table}: {\n        Row: {\n`;
  for (const c of cols) {
    out += `          ${c.column}: ${tsType(c)}${c.is_nullable ? ' | null' : ''};\n`;
  }
  out += `        };\n        Insert: {\n`;
  for (const c of cols) {
    const optional = c.is_nullable || c.has_default || c.is_generated;
    out += `          ${c.column}${optional ? '?' : ''}: ${tsType(c)}${c.is_nullable ? ' | null' : ''};\n`;
  }
  out += `        };\n        Update: {\n`;
  for (const c of cols) {
    out += `          ${c.column}?: ${tsType(c)}${c.is_nullable ? ' | null' : ''};\n`;
  }
  out += `        };\n      };\n`;
}

out += `    };\n    Views: { [key: string]: never };\n    Functions: { [key: string]: never };\n    Enums: {\n`;
for (const name of Object.keys(enums).sort()) {
  out += `      ${name}: ${enums[name].map((v) => `"${v}"`).join(' | ')};\n`;
}
out += `    };\n    CompositeTypes: { [key: string]: never };\n  };\n};\n

// Convenience helpers
export type Tables<T extends keyof Database["public"]["Tables"]> =
  Database["public"]["Tables"][T]["Row"];
export type TablesInsert<T extends keyof Database["public"]["Tables"]> =
  Database["public"]["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof Database["public"]["Tables"]> =
  Database["public"]["Tables"][T]["Update"];
export type Enums<T extends keyof Database["public"]["Enums"]> =
  Database["public"]["Enums"][T];
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out, 'utf8');
await client.end();

const tableCount = Object.keys(tables).length;
const enumCount = Object.keys(enums).length;
console.log(`Wrote ${outFile}`);
console.log(`  ${tableCount} tables, ${enumCount} enums`);
